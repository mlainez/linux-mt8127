#ifndef __SOC_MEDIATEK_MT8127_MMSYS_H
#define __SOC_MEDIATEK_MT8127_MMSYS_H

#define MT8127_DISP_REG_CONFIG_DISP_OVL_MOUT_EN	0x030
#define MT8127_DISP_REG_CONFIG_DISP_OUT_SEL	0x04c
#define MT8127_DISP_REG_CONFIG_DPI0_SEL		0x054
#define MT8127_DISP_REG_CONFIG_DPI1_SEL		0x064
#define MT8127_MMSYS_SW0_RST_B			0x138

#define MT8127_OVL_MOUT_EN_RDMA0		BIT(0)
#define MT8127_OVL_MOUT_EN_MASK			GENMASK(1, 0)

/* DISP_OUT_SEL: [1:0] selects the BLS output, [3:2] the RDMA1 output */
#define MT8127_OUT_SEL_DSI0			0
#define MT8127_OUT_SEL_DPI0			1
#define MT8127_OUT_SEL_DPI1			2
#define MT8127_BLS_OUT(sel)			((sel) << 0)
#define MT8127_BLS_OUT_MASK			GENMASK(1, 0)
#define MT8127_RDMA1_OUT(sel)			((sel) << 2)
#define MT8127_RDMA1_OUT_MASK			GENMASK(3, 2)

#define MT8127_DPI_SEL_IN_BLS			0
#define MT8127_DPI_SEL_IN_RDMA1			BIT(0)
#define MT8127_DPI_SEL_IN_MASK			BIT(0)

static const struct mtk_mmsys_routes mt8127_mmsys_routing_table[] = {
	MMSYS_ROUTE(OVL0, RDMA0,
		    MT8127_DISP_REG_CONFIG_DISP_OVL_MOUT_EN, MT8127_OVL_MOUT_EN_MASK,
		    MT8127_OVL_MOUT_EN_RDMA0),
	MMSYS_ROUTE(BLS, DSI0,
		    MT8127_DISP_REG_CONFIG_DISP_OUT_SEL, MT8127_BLS_OUT_MASK,
		    MT8127_BLS_OUT(MT8127_OUT_SEL_DSI0)),
	MMSYS_ROUTE(BLS, DPI0,
		    MT8127_DISP_REG_CONFIG_DISP_OUT_SEL, MT8127_BLS_OUT_MASK,
		    MT8127_BLS_OUT(MT8127_OUT_SEL_DPI0)),
	MMSYS_ROUTE(BLS, DPI0,
		    MT8127_DISP_REG_CONFIG_DPI0_SEL, MT8127_DPI_SEL_IN_MASK,
		    MT8127_DPI_SEL_IN_BLS),
	MMSYS_ROUTE(BLS, DPI1,
		    MT8127_DISP_REG_CONFIG_DISP_OUT_SEL, MT8127_BLS_OUT_MASK,
		    MT8127_BLS_OUT(MT8127_OUT_SEL_DPI1)),
	MMSYS_ROUTE(BLS, DPI1,
		    MT8127_DISP_REG_CONFIG_DPI1_SEL, MT8127_DPI_SEL_IN_MASK,
		    MT8127_DPI_SEL_IN_BLS),
	MMSYS_ROUTE(RDMA1, DSI0,
		    MT8127_DISP_REG_CONFIG_DISP_OUT_SEL, MT8127_RDMA1_OUT_MASK,
		    MT8127_RDMA1_OUT(MT8127_OUT_SEL_DSI0)),
	MMSYS_ROUTE(RDMA1, DPI0,
		    MT8127_DISP_REG_CONFIG_DISP_OUT_SEL, MT8127_RDMA1_OUT_MASK,
		    MT8127_RDMA1_OUT(MT8127_OUT_SEL_DPI0)),
	MMSYS_ROUTE(RDMA1, DPI0,
		    MT8127_DISP_REG_CONFIG_DPI0_SEL, MT8127_DPI_SEL_IN_MASK,
		    MT8127_DPI_SEL_IN_RDMA1),
	MMSYS_ROUTE(RDMA1, DPI1,
		    MT8127_DISP_REG_CONFIG_DISP_OUT_SEL, MT8127_RDMA1_OUT_MASK,
		    MT8127_RDMA1_OUT(MT8127_OUT_SEL_DPI1)),
	MMSYS_ROUTE(RDMA1, DPI1,
		    MT8127_DISP_REG_CONFIG_DPI1_SEL, MT8127_DPI_SEL_IN_MASK,
		    MT8127_DPI_SEL_IN_RDMA1),
};

#endif /* __SOC_MEDIATEK_MT8127_MMSYS_H */
